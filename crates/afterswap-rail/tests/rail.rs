#[test]
fn attestation_signs_and_verifies() {
    let key = AttestKey::from_seed(SEED);
    let r = attest(fixture(), &key);
    assert!(verify_attestation(&r, &key.public()).is_ok());
}

#[test]
fn wrong_key_and_tampering_both_fail() {
    let key = AttestKey::from_seed(SEED);
    let other = AttestKey::from_seed([8; 32]);
    let r = attest(fixture(), &key);
    assert_eq!(verify_attestation(&r, &other.public()), Err(RailError::Attestation));
    let mut tampered = r.clone();
    tampered.t_ms += 1;
    assert_eq!(verify_attestation(&tampered, &key.public()), Err(RailError::Attestation));
}

/// Domain separation: a signature over the *raw* content digest — no domain
/// tag — must not verify as an attestation. This is the property that keeps
/// rail records uncollidable with anything else the key holder signs.
#[test]
fn a_signature_without_the_domain_tag_does_not_verify() {
    use ed25519_dalek::{Signer as _, SigningKey};
    let signing = SigningKey::from_bytes(&SEED);
    let mut r = fixture();
    let naked = signing.sign(&content_digest(&r));
    r.attestation = naked.to_bytes();
    let key = AttestKey::from_seed(SEED);
    assert_eq!(verify_attestation(&r, &key.public()), Err(RailError::Attestation));
}

// -------------------------------------------------------------------------
// Chain
// -------------------------------------------------------------------------

fn chain_of(n: u64) -> Vec<AuditRecord> {
    let key = AttestKey::from_seed(SEED);
    let mut out: Vec<AuditRecord> = Vec::new();
    for i in 0..n {
        let mut r = fixture();
        r.seq = i;
        let linked = link(r, out.last());
        out.push(attest(linked, &key));
    }
    out
}

#[test]
fn a_well_formed_chain_verifies_with_no_gaps() {
    let c = chain_of(4);
    assert_eq!(c[0].prev_hash, ZERO_HASH);
    let report = verify_chain(&c, None).expect("verifies");
    assert_eq!(report.records, 4);
    assert!(report.gaps.is_empty());
    assert_eq!(report.tip, record_hash(&c[3]));
}

#[test]
fn tampering_with_a_middle_record_breaks_the_chain_after_it() {
    let mut c = chain_of(4);
    c[1].t_ms += 1;
    let err = verify_chain(&c, None).expect_err("must break");
    // The record after the tampered one no longer links.
    assert_eq!(err, RailError::ChainLink(c[2].seq));
}

/// Gaps are reported, not rejected: a dropped cycle is a fact about capture
/// and hiding it would condition the log on success.
#[test]
fn seq_gaps_are_visible_but_valid() {
    let key = AttestKey::from_seed(SEED);
    let mut c = chain_of(2);
    let mut r = fixture();
    r.seq = 10; // gap: 1 -> 10
    let linked = link(r, c.last());
    c.push(attest(linked, &key));
    let report = verify_chain(&c, None).expect("gaps are not errors");
    assert_eq!(report.gaps, vec![(1, 10)]);
}

#[test]
fn non_monotonic_seq_is_rejected() {
    let mut c = chain_of(3);
    c[2].seq = c[1].seq; // equal is as bad as decreasing
    assert_eq!(verify_chain(&c, None), Err(RailError::SeqOrder(c[2].seq)));
}

#[test]
fn resuming_from_a_known_tip_checks_the_link() {
    let c = chain_of(4);
    let (head, tail) = c.split_at(2);
    let head_report = verify_chain(head, None).expect("head");
    assert!(verify_chain(tail, Some(head_report.tip)).is_ok());
    assert_eq!(
        verify_chain(tail, Some([5; 32])),
        Err(RailError::ChainLink(tail[0].seq))
    );
}

// -------------------------------------------------------------------------
// Merkle
// -------------------------------------------------------------------------

#[test]
fn every_leaf_proves_inclusion_at_many_sizes() {
    for n in [1usize, 2, 3, 4, 5, 7, 8, 33] {
        let leaves: Vec<[u8; 32]> = (0..n).map(|i| [i as u8; 32]).collect();
        let root = merkle_root(&leaves).expect("root");
        for (i, leaf) in leaves.iter().enumerate() {
            let proof = merkle_proof(&leaves, i).expect("proof");
            assert!(merkle_verify(leaf, &proof, &root), "n={n} i={i}");
        }
    }
}

#[test]
fn a_wrong_leaf_or_wrong_root_fails() {
    let leaves: Vec<[u8; 32]> = (0..5u8).map(|i| [i; 32]).collect();
    let root = merkle_root(&leaves).expect("root");
    let proof = merkle_proof(&leaves, 2).expect("proof");
    assert!(!merkle_verify(&[99; 32], &proof, &root));
    assert!(!merkle_verify(&leaves[2], &proof, &[0; 32]));
    // A proof for one index does not verify another leaf.
    assert!(!merkle_verify(&leaves[3], &proof, &root));
}

#[test]
fn empty_segments_have_no_root_and_bad_indices_are_refused() {
    assert_eq!(merkle_root(&[]), Err(RailError::Empty));
    let leaves = [[1u8; 32]];
    assert_eq!(merkle_proof(&leaves, 1), Err(RailError::MerkleIndex));
}

/// A leaf value must not be usable as an interior node (RFC 6962-style
/// domain separation): the root of [a, b] is not the plain hash of the two
/// leaf hashes without prefixes.
#[test]
fn leaf_and_node_domains_are_separated() {
    let leaves: Vec<[u8; 32]> = vec![[1; 32], [2; 32]];
    let root = merkle_root(&leaves).expect("root");
    let mut h = blake3::Hasher::new();
    h.update(&[1u8; 32]);
    h.update(&[2u8; 32]);
    assert_ne!(root, *h.finalize().as_bytes());
}

