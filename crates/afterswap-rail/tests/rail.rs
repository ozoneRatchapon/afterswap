// -------------------------------------------------------------------------
// Canonical encoding
// -------------------------------------------------------------------------

/// Golden digest. Generated by this implementation, so it is a *change
/// detector*, not independent verification: if this fails, the byte layout
/// moved, and every existing signature and anchor is invalid. That is either
/// a release-noted schema-version bump or a bug — never a test to update
/// casually.
#[test]
fn canonical_digest_is_pinned() {
    let d = content_digest(&fixture());
    let hex: String = d.iter().map(|b| format!("{b:02x}")).collect();
    assert_eq!(hex, "49ceb0d4f1e7915efd9d1f218ac614f9417ffc36739c15320519c7225821c9a6");
}

type Mutation = Box<dyn Fn(&mut AuditRecord)>;

#[test]
fn every_field_reaches_the_digest() {
    let base = content_digest(&fixture());
    let mutations: Vec<Mutation> = vec![
        Box::new(|r| r.seq += 1),
        Box::new(|r| r.prev_hash[0] ^= 1),
        Box::new(|r| r.t_ms += 1),
        Box::new(|r| r.instrument.push('X')),
        Box::new(|r| r.quotes[0].out_amount = "108036855".into()),
        Box::new(|r| r.quotes[1].context_slot = None),
        Box::new(|r| r.quotes[1].latency_us += 1),
        Box::new(|r| {
            r.quotes[0].evidence = QuoteEvidence::ProviderSigned {
                sig_headers: "tampered".into(),
                body_sha256: [9; 32],
            }
        }),
        Box::new(|r| r.policy_fingerprint ^= 1),
        Box::new(|r| r.decision.chosen_venue = "jupiter".into()),
        Box::new(|r| r.decision.evaluated[1].net_out = "1".into()),
        Box::new(|r| r.fill = None),
        Box::new(|r| {
            if let Some(f) = &mut r.fill {
                f.fee_lamports += 1;
            }
        }),
    ];
    for (i, m) in mutations.iter().enumerate() {
        let mut r = fixture();
        m(&mut r);
        assert_ne!(content_digest(&r), base, "mutation {i} did not move the digest");
    }
}

/// The attestation is excluded from the content digest (a record cannot sign
/// its own signature) but included in the record hash (the chain commits to
/// records as published).
#[test]
fn attestation_is_outside_content_but_inside_record_hash() {
    let mut a = fixture();
    let mut b = fixture();
    a.attestation = [1; 64];
    b.attestation = [2; 64];
    assert_eq!(content_digest(&a), content_digest(&b));
    assert_ne!(record_hash(&a), record_hash(&b));
}

/// JSON is transport, canonical bytes are truth — but a record must survive
/// the trip between them with its digest intact, or a stored record could
/// not be re-verified.
#[test]
fn json_round_trip_preserves_the_digest() {
    let r = attest(fixture(), &AttestKey::from_seed(SEED));
    let json = serde_json::to_string(&r).expect("serialises");
    // Hashes travel as hex, not number arrays: auditors read these.
    assert!(json.contains("\"prev_hash\":\"0303"), "hex serialisation");
    let back: AuditRecord = serde_json::from_str(&json).expect("round trips");
    assert_eq!(back, r);
    assert_eq!(content_digest(&back), content_digest(&r));
    assert_eq!(record_hash(&back), record_hash(&r));
}

