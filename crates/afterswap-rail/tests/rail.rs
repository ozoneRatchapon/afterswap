//! Regression tests for the rail record format.
//!
//! The canonical encoding is the load-bearing artifact: every signature and
//! every anchor stands on it, and an accidental byte-layout change would
//! invalidate five years of records. So these tests pin it three ways —
//! a golden digest, mutation sensitivity, and JSON round-trip parity.

use afterswap_rail::{
    AttestKey, AuditRecord, EvaluatedVenue, FillRef, QuoteEvidence, RailError, RouteDecision,
    VenueQuote, ZERO_HASH, attest, content_digest, link, merkle_proof, merkle_root, merkle_verify,
    record_hash, rule_v1_fingerprint, verify_attestation, verify_chain, verify_record,
};
use sha2::{Digest as _, Sha256};

const SEED: [u8; 32] = [7; 32];

/// Standard-alphabet base64 encode, test-side counterpart of the crate's
/// decoder.
fn b64(data: &[u8]) -> String {
    const A: &[u8] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut out = String::new();
    for chunk in data.chunks(3) {
        let b = [chunk[0], *chunk.get(1).unwrap_or(&0), *chunk.get(2).unwrap_or(&0)];
        let n = (u32::from(b[0]) << 16) | (u32::from(b[1]) << 8) | u32::from(b[2]);
        out.push(A[(n >> 18) as usize & 63] as char);
        out.push(A[(n >> 12) as usize & 63] as char);
        out.push(match chunk.len() {
            1 => '=',
            _ => A[(n >> 6) as usize & 63] as char,
        });
        out.push(match chunk.len() {
            3 => A[n as usize & 63] as char,
            _ => '=',
        });
    }
    out
}

fn observed(body: &[u8]) -> QuoteEvidence {
    QuoteEvidence::Observed {
        body_b64: b64(body),
        body_sha256: Sha256::digest(body).into(),
    }
}

